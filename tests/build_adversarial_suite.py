def main() -> None:
    rows = []
    seen = set()
    for case_id, label, language, category, why, text in CASES:
        normalized = " ".join(text.casefold().split())
        if case_id in seen:
            raise ValueError(f"duplicate id: {case_id}")
        if normalized in seen:
            raise ValueError(f"duplicate text: {case_id}")
        seen.add(case_id)
        seen.add(normalized)
        rows.append({
            "id": case_id,
            "text": text,
            "label": label,
            "language": language,
            "category": category,
            "why": why,
        })
    path = Path(__file__).resolve().parent / "adversarial_suite.json"
    with open(path, "w", encoding="utf-8") as fh:
        json.dump(rows, fh, ensure_ascii=False, indent=2)
    spam = sum(1 for r in rows if r["label"] == "spam")
    print(f"wrote {len(rows)} cases to {path} ({spam} spam, {len(rows) - spam} ham)")


if __name__ == "__main__":
    main()
